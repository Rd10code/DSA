public class And_operator {
    public static void main(String[] args) {
        // Binaray AND
        System.out.println((5&6));
        // bInary OR
        System.out.println((5| 6));
        // Binaray XOR
        System.out.println((5 ^ 6));

        // Binaray One's Compliment
        System.out.println(~5);
        System.out.println(~0);

        //Binaray left shift
        System.out.println(5<<2);
        //Binaray Right shift
        System.out.print(6>>1);
    }    
}
