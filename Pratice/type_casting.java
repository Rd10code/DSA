public class type_casting{
    public static void main(String arg[]){
        int a = 257;
        byte b = (byte)a;
        System.out.println(a);
        System.out.println(b);

        byte c =30;
        byte d = 20;
        int result =c*d;
        System.out.println(result);
        System.out.println();
    }
}